#!/usr/bin/env bun
/**
 * Vendors the Playwright MCP tool contract into src/browser/contract.generated.ts.
 *
 * The CLI ships the same pin as the Kilo browser extension, so both backends expose one tool list and one SHA-256.
 * Run this after changing the pin:
 *
 *   bun run generate:browser-contract
 *   bun run generate:browser-contract --check
 */
import fs from "node:fs/promises"
import path from "node:path"
import { spawn } from "node:child_process"
import { fileURLToPath } from "node:url"
import { entries, hash } from "../src/browser/contract-shape"
import type { Entry } from "../src/browser/contract-shape"

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const root = path.resolve(dir, "..", "..")
const output = path.join(dir, "src/browser/contract.generated.ts")
const pin = "@playwright/mcp@0.0.81"
const protocol = "2024-11-05"
const timeout = 120_000

// Mirrors apps/extension/scripts/generate-browser-tool-contract.mjs: the pinned server over stdio, so the SHA-256 is
// the same value the extension vendor uses for the handshake. The hash covers the raw tools/list result, including the
// key order of every JSON Schema, so it must not go through a client that re-serializes the payload.
const list = async () => {
  // Resolve the pinned package the way a dependent does: in a workspace it may sit under the package's own
  // node_modules rather than the repository root.
  const manifest = fileURLToPath(import.meta.resolve("@playwright/mcp/package.json"))
  const child = spawn(process.execPath, [path.join(path.dirname(manifest), "cli.js"), "--headless"], {
    stdio: ["pipe", "pipe", "pipe"],
  })
  type Response = { result?: unknown; error?: unknown }
  const pending = new Map<number, PromiseWithResolvers<Response>>()
  const send = (message: unknown) => child.stdin.write(`${JSON.stringify(message)}\n`)
  const request = (id: number, method: string, params: unknown) => {
    const deferred = Promise.withResolvers<Response>()
    pending.set(id, deferred)
    send({ id, jsonrpc: "2.0", method, params })
    return deferred.promise
  }

  let buffer = ""
  let stderr = ""
  child.stdout.setEncoding("utf8")
  child.stderr.setEncoding("utf8")
  child.stderr.on("data", (chunk: string) => {
    stderr += chunk
  })
  child.stdout.on("data", (chunk: string) => {
    buffer += chunk
    let newline = buffer.indexOf("\n")
    while (newline !== -1) {
      const line = buffer.slice(0, newline).trim()
      buffer = buffer.slice(newline + 1)
      newline = buffer.indexOf("\n")
      if (!line) continue
      const message = JSON.parse(line) as Response & { id?: number }
      if (message.id === undefined) continue
      const settle = pending.get(message.id)
      if (!settle) continue
      pending.delete(message.id)
      settle.resolve(message)
    }
  })
  const fail = (error: Error) => {
    for (const settle of pending.values()) settle.reject(error)
    pending.clear()
  }
  child.on("error", (error) => fail(error))
  child.on("exit", (code) => fail(new Error(`${pin} exited with code ${code}\n${stderr}`)))

  const timer = setTimeout(() => {
    child.kill("SIGTERM")
    fail(new Error(`timed out after ${timeout}ms waiting for ${pin}`))
  }, timeout)

  try {
    const initialized = await request(1, "initialize", {
      capabilities: {},
      clientInfo: { name: "kilo-browser-tool-contract", version: "1.0.0" },
      protocolVersion: protocol,
    })
    if (initialized.error) throw new Error(`${pin} rejected initialize: ${JSON.stringify(initialized.error)}`)
    send({ jsonrpc: "2.0", method: "notifications/initialized" })
    const listed = await request(2, "tools/list", {})
    if (listed.error) throw new Error(`${pin} rejected tools/list: ${JSON.stringify(listed.error)}`)
    if (listed.result === undefined) throw new Error(`${pin} returned an empty tools/list result`)
    return { result: listed.result, tools: entries(listed.result) }
  } finally {
    clearTimeout(timer)
    child.kill("SIGTERM")
  }
}

async function format(file: string) {
  const proc = Bun.spawn([path.join(root, "node_modules/.bin/prettier"), "--write", file], {
    cwd: root,
    stdout: "pipe",
    stderr: "pipe",
  })
  const code = await proc.exited
  if (code !== 0) throw new Error(`prettier failed for ${file}: ${await new Response(proc.stderr).text()}`)
}

const source = (
  result: unknown,
  tools: Entry[],
) => `// Generated by bun script/generate-browser-tool-contract.ts. Do not edit by hand.
// Upstream: ${pin}
// Raw tools/list JSON SHA-256: ${hash(result)}
import type { Entry } from "./contract-shape"

export const UPSTREAM = ${JSON.stringify(pin)}

export const SHA256 = ${JSON.stringify(hash(result))}

export const ENTRIES: readonly Entry[] = ${JSON.stringify(tools, null, 2)}
`

/** Line endings are the checkout's, not the contract's. */
const normalize = (value: string) => value.replace(/\r\n/g, "\n")

const main = async () => {
  const check = process.argv.includes("--check")
  const { result, tools } = await list()
  const text = source(result, tools)

  if (!check) {
    await fs.writeFile(output, text)
    await format(output)
    console.log(`wrote ${path.relative(dir, output)} with ${tools.length} tools, sha256 ${hash(result)}`)
    return
  }

  const committed = await fs.readFile(output, "utf8").catch(() => "")
  // The probe sits beside the output, where prettier resolves the same config; it is removed even when formatting
  // throws, so a failed check never leaves a stray module for tsc and lint to pick up.
  const probe = `${output}.probe.ts`
  let formatted: string
  try {
    await fs.writeFile(probe, text)
    await format(probe)
    formatted = await fs.readFile(probe, "utf8")
  } finally {
    await fs.rm(probe, { force: true })
  }
  // A CRLF checkout is not a drift: compare the generator's own line endings.
  if (normalize(committed) !== normalize(formatted)) {
    console.error(`${path.relative(dir, output)} is out of date with ${pin}. Re-run this script.`)
    process.exitCode = 1
    return
  }
  console.log(`${path.relative(dir, output)} matches ${pin} with ${tools.length} tools`)
}

await main()
