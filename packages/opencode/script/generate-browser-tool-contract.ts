#!/usr/bin/env bun
/**
 * Vendors the Playwright MCP tool contract into src/kilocode/browser/contract.generated.ts.
 *
 * The CLI ships the same pin as the Kilo browser extension, so the two backends expose one
 * tool list. Run this after changing the pin:
 *
 *   bun run packages/opencode/script/generate-browser-tool-contract.ts
 *   bun run packages/opencode/script/generate-browser-tool-contract.ts --check
 */
import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { Client } from "@modelcontextprotocol/sdk/client/index.js"
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js"
import { entries, hash } from "../src/kilocode/browser/contract-shape"
import type { Entry } from "../src/kilocode/browser/contract-shape"

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const output = path.join(dir, "src/kilocode/browser/contract.generated.ts")
const pin = "@playwright/mcp@0.0.81"

// Mirrors apps/extension/scripts/generate-browser-tool-contract.mjs: the pinned server over stdio,
// so the SHA-256 is the same value the extension vendor uses for the handshake.
const list = async () => {
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [path.join(dir, "node_modules/@playwright/mcp/cli.js"), "--headless"],
    stderr: "ignore",
  })
  const client = new Client({ name: "kilo-browser-tool-contract", version: "1.0.0" })
  await client.connect(transport)
  try {
    const result = await client.listTools()
    return { result, tools: entries(result) }
  } finally {
    await client.close()
  }
}

async function format(file: string) {
  const binary = path.join(dir, "node_modules/.bin/prettier")
  const proc = Bun.spawn([binary, "--write", file], { cwd: dir, stdout: "pipe", stderr: "pipe" })
  const code = await proc.exited
  if (code !== 0) throw new Error(`prettier failed for ${file}: ${await new Response(proc.stderr).text()}`)
}

const source = (result: unknown, tools: Entry[]) => `// Generated by bun script/generate-browser-tool-contract.ts. Do not edit by hand.
// Upstream: ${pin}
// Raw tools/list JSON SHA-256: ${hash(result)}
import type { Entry } from "./contract-shape"

export const UPSTREAM = ${JSON.stringify(pin)}

export const SHA256 = ${JSON.stringify(hash(result))}

export const ENTRIES: readonly Entry[] = ${JSON.stringify(tools, null, 2)}
`

const main = async () => {
  const check = process.argv.includes("--check")
  const { result, tools } = await list()
  const text = source(result, tools)

  if (!check) {
    await fs.writeFile(output, text)
    await format(output)
    console.log(`wrote ${path.relative(dir, output)} with ${tools.length} tools, sha256 ${hash(result)}`)
    return
  }

  const committed = await fs.readFile(output, "utf8").catch(() => "")
  const probe = `${output}.probe.ts`
  await fs.writeFile(probe, text)
  await format(probe)
  const formatted = await fs.readFile(probe, "utf8")
  await fs.rm(probe, { force: true })
  if (committed !== formatted) {
    console.error(`${path.relative(dir, output)} is out of date with ${pin}. Re-run this script.`)
    process.exitCode = 1
    return
  }
  console.log(`${path.relative(dir, output)} matches ${pin} with ${tools.length} tools`)
}

await main()
